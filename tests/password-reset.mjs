// Forgot-password checks. Run after test:flow against the same local server: npm run dev, npm run test:flow, npm run test:password.
const base = process.env.TEST_URL || 'http://localhost:8788';
if (!['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname)) throw new Error('Use a local, disposable test database');
let n = 0;
const ok = (c, m) => { n++; console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const call = async (m, u, t, b) => { const r = await fetch(base + u, { method: m, headers: { 'Content-Type': 'application/json', ...(t ? { Authorization: 'Bearer ' + t } : {}) }, body: b ? JSON.stringify(b) : undefined }); return [r.status, await r.json().catch(() => null)]; };
const tag = Date.now();
let [s, d] = await call('POST', '/api/login', null, { username: process.env.TEST_ADMIN_USERNAME || 'smokeadmin', password: process.env.TEST_ADMIN_PASSWORD || 'local-smoke-password' });
const O = d.token;
[s, d] = await call('POST', '/api/users', O, { name: 'Forgetful', username: 'forget' + tag, password: 'secret12', email: `f${tag}@example.test` });
const uid = d.id; ok(s === 200 && d.email === `f${tag}@example.test`, 'admin can set a recovery email');
[s, d] = await call('POST', '/api/password/forgot', null, { username: 'nobody' + tag });
const generic = d.message; ok(s === 200, 'unknown user gets the generic answer');
[s, d] = await call('POST', '/api/password/forgot', null, { username: 'forget' + tag });
ok(s === 200 && d.message === generic, 'known user gets the same answer (no account discovery)');
[s, d] = await call('GET', '/api/password/requests', O);
ok(d.some((r) => r.user_id === uid), 'admin sees the reset request');
[s, d] = await call('GET', '/api/notifications', O);
ok(d.some((x) => x.type === 'reset_request'), 'admin notified about the request');
const [, before] = await call('POST', '/api/login', null, { username: 'forget' + tag, password: 'secret12' });
[s, d] = await call('POST', `/api/users/${uid}/temp-password`, O);
const temp = d.password; ok(s === 200 && /^[a-z]+-\d{4}-[a-z]+$/.test(temp), 'temporary password created');
[s] = await call('GET', '/api/me', before.token); ok(s === 401, 'old sessions signed out');
[s, d] = await call('POST', '/api/login', null, { username: 'forget' + tag, password: temp });
const T = d.token; ok(d.user.must_change_password === true, 'must choose a new password after temp login');
[s, d] = await call('POST', '/api/me/password', T, { current: temp, password: temp }); ok(s === 400, 'cannot keep the temporary password');
[s, d] = await call('POST', '/api/me/password', T, { current: temp, password: 'brand-new-pw' });
[s, d] = await call('GET', '/api/me', T); ok(d.user.must_change_password === false, 'flag cleared after choosing a password');
[s, d] = await call('GET', '/api/password/requests', O); ok(!d.some((r) => r.user_id === uid), 'request marked handled');
[s] = await call('POST', '/api/password/reset', null, { token: 'f'.repeat(64), password: 'whatever1' }); ok(s === 400, 'bad reset link rejected');
for (let i = 0; i < 4; i++) await call('POST', '/api/password/forgot', null, { username: 'forget' + tag });
[s, d] = await call('GET', '/api/notifications', O);
ok(d.filter((x) => x.type === 'reset_request' && x.body.includes('forget' + tag)).length <= 3, 'rate limited to 3 requests an hour');
[s, d] = await call('POST', '/api/users', O, { name: 'Plain', username: 'plainadm' + tag, password: 'secret12', role: 'superadmin' });
const [, pa] = await call('POST', '/api/login', null, { username: 'plainadm' + tag, password: 'secret12' });
const ownerId = (await call('GET', '/api/me', O))[1].user.id;
[s] = await call('POST', `/api/users/${ownerId}/temp-password`, pa.token); ok(s === 403, 'super admin cannot reset an owner');
console.log(n, 'checks');
